export function poseDadaoViewArm(hand, side, shoulder, anchor, rotation, pole, pose, narrow) {
  const phase = pose.phase === 'ready' ? 'draw' : pose.phase, frames = keys[phase];
  if (!frames) throw new Error(`Unknown dadao view phase: ${pose.phase}`);
  const t = pose.phase === 'ready' ? frames.length - 1 : THREE.MathUtils.clamp(pose.progress, 0, 1) * (frames.length - 1);
  const index = Math.min(frames.length - 2, Math.floor(t)), weight = t - index;
  const sample = column => THREE.MathUtils.lerp(frames[index][column], frames[index + 1][column], weight);
  const theta = side === 'right' ? THREE.MathUtils.lerp(sample(0), sample(2), narrow) : sample(4);
  const phi = side === 'right' ? THREE.MathUtils.lerp(sample(1), sample(3), narrow) : sample(5);
  const axis = new THREE.Vector3(0, 1, 0).applyQuaternion(rotation);
  const y = new THREE.Vector3(1, 0, 0).applyQuaternion(rotation).multiplyScalar(Math.cos(theta))
    .addScaledVector(new THREE.Vector3(0, 0, 1).applyQuaternion(rotation), Math.sin(theta));
  const z = new THREE.Vector3().crossVectors(axis, y), grip = new THREE.Vector3(...hand.userData.throwableGrips.dadao);
  const wrist = anchor.clone().addScaledVector(axis, -grip.x).addScaledVector(y, -grip.y).addScaledVector(z, -grip.z);
  const direction = wrist.clone().sub(shoulder).normalize();
  const out = pole.clone().addScaledVector(direction, -pole.dot(direction)).normalize();
  const across = new THREE.Vector3().crossVectors(direction, out);
  const bend = out.multiplyScalar(Math.cos(phi)).addScaledVector(across, Math.sin(phi));
  const facing = new THREE.Quaternion().setFromRotationMatrix(new THREE.Matrix4().makeBasis(axis, y, z));
  hand.poseArm(shoulder, wrist, facing, bend);
  return facing;
}
