export function poseDadaoViewArm(hand, side, shoulder, anchor, rotation, pole, pose) {
  const phase = pose.phase === 'ready' ? 'draw' : pose.phase, frames = keys[phase];
  if (!frames) throw new Error(`Unknown dadao view phase: ${pose.phase}`);
  const t = pose.phase === 'ready' ? frames.length - 1 : THREE.MathUtils.clamp(pose.progress, 0, 1) * (frames.length - 1);
  const index = Math.min(frames.length - 2, Math.floor(t)), weight = t - index;
  const column = side === 'right' ? 0 : 2;
  const theta = THREE.MathUtils.lerp(frames[index][column], frames[index + 1][column], weight);
  const phi = THREE.MathUtils.lerp(frames[index][column + 1], frames[index + 1][column + 1], weight);
  const grip = new THREE.Vector3(...hand.userData.throwableGrips.dadao);
  const target = dadaoCalibratedGrip(anchor, rotation, shoulder, grip, pole, theta, phi);
  hand.poseArm(shoulder, target.wrist, target.rotation, target.pole);
  return target.rotation;
}
