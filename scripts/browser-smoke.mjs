import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join } from 'node:path';
import { MATCH_SECONDS } from '../src/core.js';

const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const snapshot = () => page.evaluate(() => window.__battle);
const key = async (code, ms = 0) => {
  await page.keyboard.down(code);
  if (ms) await page.waitForTimeout(ms);
  await page.keyboard.up(code);
};
const artifacts = process.env.ARTIFACT_DIR;

try {
  await page.goto(process.env.GAME_URL || 'http://127.0.0.1:5173');
  await page.waitForFunction(() => window.__battle?.state === 'menu');
  if (artifacts) {
    await mkdir(artifacts, { recursive: true });
    await page.screenshot({ path: join(artifacts, 'battle-menu.png') });
  }
  await page.locator('#deploy').click();
  await page.waitForFunction(() => window.__battle.state === 'playing');
  let data = await snapshot();
  assert.equal(data.type, 'infantry');
  assert.equal(data.allies.length, 4);
  assert.equal(data.allies[0].role, 'engineer');
  assert.equal(data.spawnId, 'china-base');
  assert.ok(data.spawnEvents.filter(event => event.team === 'enemy').every(event => event.pointId === 'japan-base'));
  await page.mouse.down({ button: 'right' });
  await page.waitForTimeout(350);
  data = await snapshot();
  assert.equal(data.aiming, true);
  assert.ok(data.fov < 52, 'RMB transitions to a magnified sight picture');
  assert.equal(await page.locator('#crosshair').isVisible(), false, 'iron sights replace the hip-fire crosshair');
  await key('Shift', 200);
  assert.ok((await snapshot()).breath < 1, 'Shift steadies aim using breath');
  if (artifacts) await page.screenshot({ path: join(artifacts, 'battle-aiming.png') });
  await page.mouse.up({ button: 'right' });
  await key('Control');
  assert.equal((await snapshot()).stance, 'crouched');
  await key('z');
  assert.equal((await snapshot()).stance, 'prone');
  await key('z');
  assert.equal((await snapshot()).stance, 'standing');
  await key('2');
  assert.equal((await snapshot()).construction.tool, true);
  await page.mouse.down({ button: 'right' });
  await page.mouse.up({ button: 'right' });
  assert.equal((await snapshot()).construction.blueprint, true);
  await page.mouse.down();
  await page.waitForTimeout(600);
  await page.mouse.up();
  assert.equal((await snapshot()).spawnPoints.filter(point => point.kind === 'rally' && point.team === 'friendly').length, 0, 'interrupted construction does not create a spawn point');
  await page.mouse.down();
  await page.waitForFunction(() => window.__battle.spawnPoints.some(point => point.kind === 'rally' && point.team === 'friendly'), null, { timeout: 12000 });
  await page.mouse.up();
  const builtRally = (await snapshot()).spawnPoints.find(point => point.kind === 'rally' && point.team === 'friendly');
  assert.equal(builtRally.health, 120, 'engineer builds a functional rally point');
  if (artifacts) await page.screenshot({ path: join(artifacts, 'battle-engineer.png') });
  await key('1');
  await page.mouse.down({ button: 'right' });
  await page.evaluate(() => document.dispatchEvent(new MouseEvent('mousemove', { movementY: 132 })));
  await page.waitForTimeout(400);
  for (let shot = 0; shot < 2; shot++) {
    await page.mouse.down();
    await page.waitForTimeout(100);
    await page.mouse.up();
    await page.waitForTimeout(700);
  }
  assert.equal((await snapshot()).spawnPoints.find(point => point.id === builtRally.id).health, 0, 'rally point is destructible');
  await page.evaluate(() => document.dispatchEvent(new MouseEvent('mousemove', { movementY: -132 })));
  await page.mouse.up({ button: 'right' });
  await key('r');
  await page.waitForFunction(() => window.__battle.ammo === 5 && window.__battle.rifle.action === 'idle', null, { timeout: 6000 });
  const beforeMove = await snapshot();
  await key('w', 700);
  data = await snapshot();
  const moveSeconds = data.time - beforeMove.time;
  const distance = beforeMove.position.z - data.position.z;
  assert.ok(distance > 1, 'W moves the player with weighted acceleration');
  assert.ok(Math.abs(distance - 3.15 * (moveSeconds - 3.15 / 16)) < .18, 'forward displacement matches the calibrated jog speed and acceleration');
  await page.mouse.down();
  await page.waitForTimeout(100);
  await page.mouse.up();
  const firedAmmo = (await snapshot()).ammo;
  assert.ok(firedAmmo < 5, 'rifle fires');
  await key('y');
  assert.equal((await snapshot()).current, 1);
  assert.equal((await snapshot()).ammo, 5);
  await key('y');
  await key('y');
  await key('y');
  assert.equal((await snapshot()).current, 0);
  assert.equal((await snapshot()).ammo, firedAmmo, 'switching retains ammunition');
  await key('r');
  await page.waitForFunction(() => window.__battle.ammo === 5 && window.__battle.rifle.action === 'idle', null, { timeout: 6000 });
  assert.equal((await snapshot()).ammo, 5, 'reload refills the magazine');
  if (artifacts) await page.screenshot({ path: join(artifacts, 'battle-infantry.png') });
  await key('x');
  assert.ok(['advance', 'hold'].includes((await snapshot()).allies[1].order), 'X sends contextual orders');
  await key('x', 500);
  assert.equal((await snapshot()).allies[1].order, 'follow', 'holding X cancels orders');
  await page.keyboard.down('Tab');
  assert.equal(await page.locator('#scoreboard').isVisible(), true);
  assert.equal((await snapshot()).state, 'playing', 'Tab shows scores without pausing');
  await page.keyboard.up('Tab');
  assert.equal(await page.locator('#scoreboard').isVisible(), false);
  await key('Escape');
  await page.waitForFunction(() => window.__battle.state === 'pause');
  const paused = await snapshot();
  await page.waitForTimeout(400);
  assert.equal((await snapshot()).time, paused.time, 'pause freezes the simulation');
  assert.equal(await page.locator('#redeploy-choices').isVisible(), false, 'living squad cannot redeploy from pause');
  await page.evaluate(() => document.querySelector('#redeploy-choices [data-type="tank"]').click());
  assert.equal((await snapshot()).type, 'infantry', 'deployment guard rejects hidden button invocation');
  assert.equal((await snapshot()).deployments, 1);
  await page.locator('#resume').click();
  assert.equal((await snapshot()).current, 0, 'resume keeps the selected member');
  await key('Escape');
  await page.locator('#back-menu').click();
  await page.locator('#squad-choices [data-type="mortar"]').click();
  await page.locator('#deploy').click();
  assert.equal((await snapshot()).type, 'mortar');
  assert.equal((await snapshot()).allies.length, 3, 'mortar team has multiple members');
  await key('y');
  assert.equal((await snapshot()).current, 1, 'Y switches mortar crew');
  await page.waitForTimeout(400);
  await page.mouse.down();
  await page.waitForTimeout(150);
  await page.mouse.up();
  assert.equal((await snapshot()).ammo, 0, 'mortar launches a shell');
  await page.waitForTimeout(3500);
  assert.equal((await snapshot()).state, 'playing', 'mortar impact completes without runtime errors');
  await key('Escape');
  await page.locator('#back-menu').click();
  await page.locator('#squad-choices [data-type="plane"]').click();
  await page.locator('#deploy').click();
  data = await snapshot();
  assert.equal(data.type, 'plane');
  const planeZ = data.position.z;
  await key('Space', 500);
  data = await snapshot();
  assert.ok(data.position.y > 27, 'aircraft climbs');
  assert.ok(data.position.z < planeZ - 2, 'aircraft moves forward');
  await page.mouse.down();
  await page.waitForTimeout(350);
  await page.mouse.up();
  assert.ok((await snapshot()).ammo < 60, 'aircraft cannon fires');
  await page.keyboard.down('Control');
  await page.waitForFunction(() => window.__battle.state === 'dead', null, { timeout: 8000 });
  await page.keyboard.up('Control');
  data = await snapshot();
  assert.ok(data.allies.every(actor => actor.health === 0));
  assert.equal(await page.locator('#redeploy-choices').isVisible(), true, 'wiped squad opens deployment choices');
  assert.equal(await page.locator('#resume').isVisible(), false, 'dead squad cannot resume');
  assert.equal(await page.locator('#redeploy-choices [data-type="plane"]').isDisabled(), true, 'the just-wiped squad cannot immediately respawn');
  assert.equal(await page.locator('#redeploy-choices [data-type="infantry-reserve"]').isEnabled(), true, 'another infantry squad is a separate reserve choice');
  assert.equal(await page.locator('#confirm-deploy').isDisabled(), true, 'deployment requires a squad selection');
  const deathRemaining = data.remaining;
  await page.waitForTimeout(350);
  assert.ok((await snapshot()).remaining < deathRemaining, 'the battlefield keeps running while choosing a new squad');
  await page.waitForFunction(() => window.__battle.spawnEvents.some(event => event.team === 'enemy' && event.pointId.startsWith('enemy-rally-')), null, { timeout: 45000 });
  data = await snapshot();
  assert.ok(data.spawnPoints.some(point => point.kind === 'rally' && point.team === 'enemy' && point.health > 0), 'enemy engineers build a forward rally');
  assert.ok(data.spawnEvents.filter(event => event.team === 'enemy').length > 8, 'enemy reinforcements enter from registered spawns');
  for (const event of data.spawnEvents) {
    assert.ok(Math.hypot(event.x - event.pointX, event.z - event.pointZ) < 4, 'every actor entered at its registered spawn formation');
  }
  await page.locator('#redeploy-choices [data-type="tank"]').click();
  assert.equal((await snapshot()).state, 'dead', 'selecting a squad does not instantly spawn it');
  assert.equal((await snapshot()).pendingSpawn, 'china-garage');
  if (artifacts) await page.screenshot({ path: join(artifacts, 'battle-redeployment.png') });
  await page.locator('#confirm-deploy').click();
  data = await snapshot();
  assert.equal(data.type, 'tank');
  assert.ok(data.health > 0 && data.health <= 360, 'deployed tank is alive; combat may already damage it');
  assert.equal(data.allies.length, 3, 'tank has a three-person crew');
  const crewChange = await page.evaluate(() => {
    // Observe the input handler atomically; enemy fire between frames is legitimate.
    const before = window.__battle;
    for (const type of ['keydown', 'keyup']) document.dispatchEvent(new KeyboardEvent(type, { code: 'KeyY', key: 'y', bubbles: true }));
    return { before, after: window.__battle };
  });
  assert.equal(crewChange.after.current, 1);
  assert.equal(crewChange.after.health, crewChange.before.health, 'changing crew never restores or changes hull health');
  assert.equal(data.deployments, 2);
  assert.ok(data.remaining <= deathRemaining && data.remaining < MATCH_SECONDS, 'post-wipe deployment retains match time');
  const tankZ = data.position.z;
  assert.equal(data.spawnId, 'china-garage');
  await key('w', 500);
  assert.ok((await snapshot()).position.z < tankZ - 1);
  await page.mouse.down();
  await page.waitForTimeout(150);
  await page.mouse.up();
  assert.equal((await snapshot()).ammo, 0, 'tank cannon fires');
  await key('Escape');
  await page.locator('#back-menu').click();
  assert.equal((await snapshot()).state, 'menu');
  await page.locator('#deploy').click();
  assert.ok((await snapshot()).remaining > 599, 'new match resets timer');
  assert.equal((await snapshot()).deployments, 1);
  assert.equal(await page.locator('#fatal').isVisible(), false);
  assert.deepEqual(errors, [], 'no browser runtime errors');
  console.log('PASS: registered team spawns, engineer tools/build/cancel/destruction, RMB sights, Y crews, X orders, pause, live post-wipe selection, other-squad restriction, deployment confirmation, vehicles and match restart.');
  await key('Escape');
  await page.locator('#back-menu').click();
} finally {
  await browser.close();
}
